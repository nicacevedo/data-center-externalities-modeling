def _s(**kwargs) -> dict:
    row = {k: "" for k in SOURCE_COLUMNS}
    row.update(kwargs)
    row["in_source_manifest"] = bool(kwargs.get("in_source_manifest", False))
    return row


def _q(**kwargs) -> dict:
    row = {k: "" for k in QUANTITY_COLUMNS}
    row.update(kwargs)
    pc = row["provenance_class"]
    if pc not in PROVENANCE_CLASSES:
        raise ValueError(f"Invalid provenance_class {pc!r} for {row.get('quantity_id')}")
    return row


def _m(**kwargs) -> dict:
    row = {k: "" for k in MODEL_COLUMNS}
    row.update(kwargs)
    if row["model_class"] not in MODEL_CLASSES:
        raise ValueError(f"Invalid model_class {row['model_class']!r}")
    return row


